namespace BlogMagangementSystem.Common.Enums
{
    public enum PostStatus
    {
        Active,      // The post is currently active and visible to users
        Inactive,    // The post is inactive and not visible to users
        Draft,       // The post is a draft and not yet published
        Archived,    // The post is archived and no longer actively used
        Deleted      // The post has been deleted and is no longer available
    }
}
